import { Router } from 'express';
import { upload, uploadLimiter, uploadConcurrencyLimiter, resetUploadByteCount } from '../middleware/uploadMiddleware.js';
import { optionalAuth } from '../middleware/authMiddleware.js';
import { recordPdfOperation } from '../middleware/operationAnalytics.js';
import * as c from '../controllers/pdfController.js';

const r = Router();
const protectedUpload = (handler) => [optionalAuth, recordPdfOperation, uploadLimiter, uploadConcurrencyLimiter, resetUploadByteCount, handler];
const many = protectedUpload(upload.array('files', 20));
const single = protectedUpload(upload.array('files', 1));
const editFiles = protectedUpload(upload.fields([{ name: 'files', maxCount: 1 }, { name: 'signature', maxCount: 1 }]));
const watermarkFiles = protectedUpload(upload.fields([{ name: 'files', maxCount: 1 }, { name: 'watermarkImage', maxCount: 1 }]));
const signFiles = protectedUpload(upload.fields([{ name: 'files', maxCount: 1 }, { name: 'signature', maxCount: 1 }]));

r.post('/merge', ...many, c.merge);
r.post('/split', ...many, c.split);
r.post('/extract-pages', ...many, c.split);
r.post('/remove-pages', ...many, c.removePages);
r.post('/rotate', ...many, c.rotate);
r.post('/add-watermark', ...watermarkFiles, c.watermark);
r.post('/add-page-numbers', ...many, c.pageNumbers);
r.post('/scan-to-pdf', ...many, c.scan);
r.post('/text-to-pdf', ...many, c.textToPdf);
r.post('/text-to-document', ...many, c.textToDocument);
r.get('/pdf-to-document/config', c.pdfToDocumentConfig);
r.post('/pdf-to-document', ...single, c.pdfToDocument);
r.post('/pdf-to-document/text', ...single, c.pdfToDocumentText);
r.post('/convert-to-pdf', ...many, c.convertToPdf);
r.post('/office-to-pdf', ...single, c.officeToPdf);
r.post('/pdf-to-powerpoint', ...single, c.pdfToPowerPoint);
r.post('/pdf-to-pdfa', ...single, c.pdfToPdfA);
r.post('/html-to-pdf', ...many, c.htmlToPdf);
r.post('/edit-pdf', ...editFiles, c.editPdf);
r.post('/protect-pdf', ...single, c.protect);
r.post('/unlock-pdf', ...single, c.unlock);
r.post('/repair-pdf', ...single, c.repair);
r.post('/clean-metadata', ...single, c.cleanMetadata);
r.post('/crop-pdf', ...single, c.crop);
r.post('/sign-pdf', ...signFiles, c.sign);
r.post('/redact-pdf', ...single, c.redact);
r.post('/form-fields', ...single, c.pdfFormFields);
r.post('/fill-form', ...single, c.fillPdfForm);
r.post('/to-jpg', ...single, c.pdfToJpg);
r.post('/to-png', ...single, c.pdfToPng);
r.post('/flatten-pdf', ...single, c.flattenPdf);
r.post('/extract-images/inspect', ...single, c.inspectExtractImages);
r.post('/extract-images', ...single, c.extractImages);
r.post('/to-markdown', ...single, c.pdfToMarkdown);
r.post('/to-excel', ...single, c.pdfToExcel);
r.post('/summarize', ...single, c.summarize);
r.post('/compare', ...many, c.compare);
r.post('/compress', ...single, c.compress);
r.get('/ocr-pdf/languages', c.ocrLanguages);
r.post('/ocr-pdf', ...single, c.ocr);

export default r;
